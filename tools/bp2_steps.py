#!/usr/bin/env python3
"""Writes docs/bp2-sketch-steps.md from the BP2 sketches themselves (src/bp2/bp2_*.cpp):
each sketch's banner, and every step's title and CHECK NOW text, exactly as the sketch prints
them. For reviewing the steps away from the bench. Run again after changing a sketch:

    python3 tools/bp2_steps.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "bp2")
OUT = os.path.join(ROOT, "docs", "bp2-sketch-steps.md")


def strings(text):
    """C string literals in text, adjacent ones joined, escapes undone."""
    out, cur, i = [], None, 0
    toks = re.finditer(r'"((?:[^"\\]|\\.)*)"|([^\s"])', text)
    for m in toks:
        if m.group(1) is not None:
            s = bytes(m.group(1), "utf-8").decode("unicode_escape").replace("%%", "%")
            cur = s if cur is None else cur + s
        else:
            if cur is not None:
                out.append(cur)
                cur = None
    if cur is not None:
        out.append(cur)
    return out


def strip_comments(src):
    """src with // and /* */ comments removed (string literals kept as they are), so a comment
    such as `// ---- (a) the relay alone` inside a step list is never taken for a step."""
    return re.sub(r'"(?:[^"\\]|\\.)*"|//[^\n]*|/\*.*?\*/',
                  lambda m: m.group(0) if m.group(0).startswith('"') else "", src, flags=re.S)


def block(src, name):
    """The text inside `name[] = { ... };`, or None."""
    m = re.search(re.escape(name) + r"\[\]\s*=\s*\{", src)
    if not m:
        return None
    depth, i = 1, m.end()
    while depth and i < len(src):
        depth += {"{": 1, "}": -1}.get(src[i], 0)
        i += 1
    return src[m.end():i - 1]


def entries(body):
    """Top-level { ... } or MACRO( ... ) entries of an array body."""
    out, depth, start = [], 0, None
    for i, ch in enumerate(body):
        if ch in "{(":
            if depth == 0:
                start = i
            depth += 1
        elif ch in "})":
            depth -= 1
            if depth == 0 and start is not None:
                out.append(body[start + 1:i])
    return out


def named_strings(src):
    """const char* kName = "..."; -> {kName: text}, for checks given by name."""
    return {m.group(1): "".join(strings(m.group(2)))
            for m in re.finditer(r'const char\*\s+(k\w+)\s*=\s*((?:"(?:[^"\\]|\\.)*"\s*)+);', src)}


def main():
    files = sorted(f for f in os.listdir(SRC) if f.startswith("bp2_") and f.endswith(".cpp"))
    lines = ["# BP2 sketches: banners and steps", "",
             "*Generated by `tools/bp2_steps.py` from `src/bp2/` - exactly what each sketch prints. "
             "Don't edit by hand; change the sketch and run the tool again.*", "",
             "Every sketch: **g** starts (nothing switches before it), **n** applies the next step, **x** = everything "
             "off. After each step: NOW LIVE (every output now), then CHECK NOW. Flash with "
             "`pio run -e <sketch> -t upload`; monitor on J23. Test points by printed label and TP number "
             "(5V TP1, 3V3RF TP2, GND TP3/TP7, TACH TP4, PWM TP5, 12V TP6, 3V3Q TP8, 3V3S TP9, EN TP10, IO0 TP11, "
             "BLW- TP12).", ""]
    for f in files:
        raw = open(os.path.join(SRC, f)).read()
        head = re.search(r"//\s*BP2 tests? ([^\n]*)", raw)
        src = strip_comments(raw)
        lines += [f"## `{f[:-4]}`" + (f" - {head.group(1).strip()}" if head else ""), ""]
        ban = block(src, "kBanner")
        if ban:
            lines += [f"> {s}" for s in strings(ban)] + [""]
        names = named_strings(src)
        steps = block(src, "kSteps")
        rows = []
        if steps:
            for e in entries(steps):
                ss = strings(e)
                ids = re.findall(r"\b(k[A-Z]\w*)\b", e)
                title = ss[0] if ss else "?"
                check = ss[1] if len(ss) > 1 else (names.get(ids[0], "") if ids else "")
                rows.append((title, check))
        else:
            t, c = block(src, "kTitles"), block(src, "kChecks")
            if t and c:
                rows = list(zip(strings(t), strings(c)))
        if rows:
            lines += ["| # | Step | Check now |", "|---|---|---|"]
            lines += [f"| {i + 1} | {t} | {c} |" for i, (t, c) in enumerate(rows)]
            lines.append("")
        else:
            lines += ["*No step list: commands as in the banner.*", ""]
    open(OUT, "w").write("\n".join(lines))
    print(f"wrote {OUT}: {len(files)} sketches")


if __name__ == "__main__":
    main()
